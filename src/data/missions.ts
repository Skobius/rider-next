export function getMissionForStatus(status: RiderStatus | null) {
  const stageId = status ? statusToStageId[status] : 'dream';
  return missions.find((mission) => mission.stageId === stageId) ?? missions[0];
}

export function getMissionByStage(stageId: string) {
  return missions.find((mission) => mission.stageId === stageId);
}
