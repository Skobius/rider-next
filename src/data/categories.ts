export function getCategoriesBySection(sectionId: SectionId) {
  return appCategories.filter((category) => category.sectionId === sectionId);
}

export function getCategoryMaterialCount(category: AppCategory) {
  return category.entityIds.length;
}

export function getCategoryMaterialCountForRegion(category: AppCategory, regionId: string) {
  if (category.entityType === 'place') {
    return places.filter((place) => place.categoryId === category.id && place.regionId === regionId).length;
  }

  if (category.entityType === 'route') {
    return routes.filter((route) => route.categoryId === category.id && route.regionId === regionId).length;
  }

  if (category.entityType === 'event') {
    return events.filter((event) => event.categoryId === category.id && event.regionId === regionId).length;
  }

  return category.entityIds.length;
}
