import type { LocalizedText } from '../shared/i18n/localizedText';

export type GuideStatus = 'draft' | 'published';

export interface Guide {
  id: string;
  slug: string;
  sectionId: string;
  categoryId: string;
  title: LocalizedText;
  cardTitle?: LocalizedText;
  shortDescription: LocalizedText;
  lead?: LocalizedText;
  keyPoints?: LocalizedText[];
  sections?: {
    title: LocalizedText;
    paragraphs?: LocalizedText[];
    bullets?: LocalizedText[];
  }[];
  checklist?: LocalizedText[];
  disclaimer?: LocalizedText;
  reviewedAt?: string;
  ctas?: {
    label: LocalizedText;
    to: string;
  }[];
  searchKeywords?: LocalizedText[];
  image?: string;
  status: GuideStatus;
}

interface GuideConfig {
  id: string;
  slug: string;
  categoryId: string;
  title: string;
  cardTitle: string;
  shortDescription: string;
  quick: string[];
  practical: string;
  when: string;
  why: string;
  advice: string;
  warning: string;
  image: string;
  related?: { label: string; to: string }[];
  keywords?: string[];
}

function lt(ru: string): LocalizedText {
  return { ru };
}

function guide(config: GuideConfig): Guide {
  return {
    id: config.id,
    slug: config.slug,
    sectionId: 'guides',
    categoryId: config.categoryId,
    title: lt(config.title),
    cardTitle: lt(config.cardTitle),
    shortDescription: lt(config.shortDescription),
    lead: lt(config.quick[0]),
    keyPoints: config.quick.map(lt),
    sections: [
      { title: lt('Практический ориентир'), paragraphs: [lt(config.practical)] },
      { title: lt('Когда проверить'), paragraphs: [lt(config.when)] },
      { title: lt('Почему это важно'), paragraphs: [lt(config.why)] },
      { title: lt('Совет MG67'), paragraphs: [lt(config.advice)] },
    ],
    disclaimer: lt(config.warning),
    reviewedAt: '2026-07-24',
    ctas: config.related?.map((item) => ({ label: lt(item.label), to: item.to })),
    searchKeywords: config.keywords?.map(lt),
    image: config.image,
    status: 'published',
  };
}

